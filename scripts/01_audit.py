import pandas as pd, numpy as np
pd.set_option('display.width', 250); pd.set_option('display.max_columns', 60); pd.set_option('display.max_colwidth', 60)
R = 'data/raw/'
bbb = pd.read_csv(R+'ball_by_ball.csv', low_memory=False)
mat = pd.read_csv(R+'matches.csv')
comp = pd.read_csv(R+'competitions.csv')
ctp = pd.read_csv(R+'competition_team_player_mapping.csv')
p11 = pd.read_csv(R+'playing_eleven.csv')
teams = pd.read_csv(R+'teams.csv')

for name, df in [('bbb',bbb),('matches',mat),('competitions',comp),('ctp_mapping',ctp),('playing_eleven',p11),('teams',teams)]:
    print(f'\n===== {name}: {df.shape}')
    print(df.dtypes.to_string())
    nulls = df.isna().sum(); print('nulls:', nulls[nulls>0].to_dict())
    print('exact duplicate rows:', df.duplicated().sum())

print('\n--- bbb key checks')
print('unique matches in bbb:', bbb.match_id.nunique(), '| in matches.csv:', mat.match_id.nunique(), '| matches rows:', len(mat))
print('bbb matches not in matches.csv:', len(set(bbb.match_id)-set(mat.match_id)))
print('matches.csv not in bbb:', len(set(mat.match_id)-set(bbb.match_id)))
print('innings values:', bbb.innings.value_counts().sort_index().to_dict())
print('dup (match,innings,innings_ball_num):', bbb.duplicated(['match_id','innings','innings_ball_num']).sum())
print('extras_type:', bbb.extras_type.value_counts(dropna=False).to_dict())
print('dismissal_type:', bbb.dismissal_type.value_counts(dropna=False).to_dict())
print('is_wicket:', bbb.is_wicket.value_counts(dropna=False).to_dict())
print('overid range:', bbb.overid.min(), bbb.overid.max(), '| over_ball_num max:', bbb.over_ball_num.max())
print('runs dist:', bbb.runs.value_counts().sort_index().to_dict())
print('extras1_runs dist:', bbb.extras1_runs.value_counts().sort_index().to_dict())
print('extras_2_runs dist:', bbb.extras_2_runs.value_counts().sort_index().to_dict())
print('pace_or_spin:', bbb.pace_or_spin.value_counts(dropna=False).to_dict())
print('batting_type:', bbb.batting_type.value_counts(dropna=False).to_dict())
print('bowling_type top:', bbb.bowling_type.value_counts(dropna=False).head(15).to_dict())
print('bowl_speed nonzero share:', (bbb.bowl_speed>0).mean())
print('stroke top:', bbb.stroke.value_counts(dropna=False).head(8).to_dict())
print('batting_order range:', bbb.batting_order.min(), bbb.batting_order.max())

print('\n--- matches checks')
print('result samples:'); print(mat.result.str.replace(r'\d+','N',regex=True).value_counts().head(25).to_string())
print('stage:', mat.stage.value_counts().to_dict())
print('knock_out:', mat.knock_out.value_counts().to_dict())
print('revised rows:', mat[['first_inn_revised_overs','second_inn_revised_overs','revised_target']].notna().sum().to_dict())
print('win_team_id null:', mat.win_team_id.isna().sum(), '| win_team_id==0:', (mat.win_team_id==0).sum())
m2 = mat.merge(comp, on='comp_id', how='left')
print('comp join misses:', m2.match_format.isna().sum())
print('matches by format:', m2.match_format.value_counts().to_dict())
print('matches by season x format:'); print(pd.crosstab(m2.season, m2.match_format))
print('IPL & other T20 comps:'); print(m2[m2.match_format=='T20'].groupby('comp_name').size())
print('date range:', mat.match_date.min(), mat.match_date.max())

print('\n--- player id consistency')
names = pd.concat([bbb[['striker_id','striker_name']].rename(columns={'striker_id':'pid','striker_name':'name'}),
                   bbb[['non_striker_id','non_striker_name']].rename(columns={'non_striker_id':'pid','non_striker_name':'name'}),
                   bbb[['bowler_id','bowler_name']].rename(columns={'bowler_id':'pid','bowler_name':'name'})]).drop_duplicates()
multi = names.groupby('pid').name.nunique(); print('ids with >1 name in bbb:', (multi>1).sum())
print(names[names.pid.isin(multi[multi>1].index)].sort_values('pid').head(20).to_string())
multi2 = names.groupby('name').pid.nunique(); print('names with >1 id in bbb:', (multi2>1).sum())
print(names[names.name.isin(multi2[multi2>1].index)].sort_values('name').head(20).to_string())
print('distinct bbb players:', names.pid.nunique(), '| ctp distinct players:', ctp.player_id.nunique())
print('bbb players missing from ctp:', len(set(names.pid)-set(ctp.player_id)))
ctpn = ctp.groupby('player_id').player_name.nunique(); print('ctp ids with >1 name:', (ctpn>1).sum())
print('p11 players missing from ctp:', len(set(p11.player_id)-set(ctp.player_id)))
print('p11 is_played:', p11.is_played.value_counts().to_dict(), '| is_impact:', p11.is_impact.value_counts().to_dict(), '| is_impact_off:', p11.is_impact_off.value_counts().to_dict())
print('p11 rows per match-team:', p11.groupby(['match_id','team_id']).size().value_counts().sort_index().to_dict())
